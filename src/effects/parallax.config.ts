/**
 * ЕДИНАЯ ТОЧКА НАСТРОЙКИ эффекта карточек (tilt + parallax). Меняете число здесь — меняются все блоки,
 * где подключён эффект: hero-карточки, инструменты, тарифы, подключение, баннер CTA.
 *
 * Модель — «карточка под стеклом»: содержимое разложено по глубине (ось Z), стекло (блик/кромка,
 * см. spotlight.ts и CSS компонентов) — неподвижный верхний слой. Разница глубин двух соседних
 * элементов и даёт параллакс при наклоне. Слой задаётся одним атрибутом в разметке:
 *
 *   data-parallax="front"   перед стеклом:  иллюстрации, плашки — едут ВСЛЕД за курсором
 *   data-parallax="mid"     на уровне стекла: тело карточки — наклоняется только вместе с ней (z=0)
 *   data-parallax="back"    под стеклом:    заголовок, текст, логотип — едут ПРОТИВ курсора
 *   data-parallax="plate"   фон карточки — всегда глубже "back", см. plateDepthFactor
 */

export type ParallaxLayerName = 'plate' | 'back' | 'mid' | 'front'

export const PARALLAX = {
  /** Дистанция до «камеры», px — задаёт силу перспективы (800–1000 выглядит естественно). */
  perspective: 900,

  /** Максимальный угол наклона карточки на каждую ось, градусы, курсор у самого края (диапазон 2–3). */
  maxAngle: 2.5,

  layers: {
    /**
     * depth — сдвиг слоя по оси Z, px (минус — вглубь, плюс — к зрителю).
     * shift — вынос слоя вбок при курсоре у края карточки, px; знак — направление: минус — слой едет
     *         ПРОТИВ курсора (как предмет за окном при взгляде сбоку), плюс — ВСЛЕД за курсором.
     */
    back: { depth: -14, shift: -4 },
    mid: { depth: 0, shift: 0 },
    front: { depth: 40, shift: 14 },
  },

  /**
   * Фон (`plate`) лежит на глубине `back.depth × plateDepthFactor` — всегда глубже `back`, иначе
   * непрозрачный фон закрыл бы содержимое, ушедшее за плоскость карточки. Поэтому глубина фона не
   * задаётся отдельным числом, а всегда выводится из `back`, и её нельзя случайно рассинхронизировать.
   * Фон не смещается вбок (курсор его не «тянет») и компенсирует перспективное уменьшение масштабом.
   */
  plateDepthFactor: 2,

  /**
   * Плавность движения — длительности CSS transition-duration (см. card-effects.ts): JS на каждое
   * событие курсора пишет ТОЧНОЕ целевое значение transform, а интерполяцию между значениями делает
   * браузер через `transition: transform` (а не JS сам считает промежуточные кадры через rAF — так
   * было раньше). followMs — пока курсор внутри карточки (быстрый отклик), releaseMs — после ухода
   * курсора (плавный, более долгий возврат).
   */
  motion: {
    followMs: 150,
    releaseMs: 320,
  },
} as const

export type ResolvedLayer = {
  shift: number
  depth: number
  /** Компенсировать перспективное уменьшение масштабом — нужно только фону. */
  fit: boolean
}

/** Переводит имя слоя из `data-parallax` в числа. `null`, если имя не из списка (опечатка в разметке). */
export function resolveLayer(name: string | undefined): ResolvedLayer | null {
  if (name === 'plate') {
    return { shift: 0, depth: PARALLAX.layers.back.depth * PARALLAX.plateDepthFactor, fit: true }
  }
  if (name === 'back' || name === 'mid' || name === 'front') {
    return { ...PARALLAX.layers[name], fit: false }
  }
  return null
}
